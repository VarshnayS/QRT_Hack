def probe(t):
    t = min(1.0, max(0.0, t)) if math.isfinite(t) else 0.0
    position = t * (len(AMPLITUDES) - 1)
    left = int(position)
    right = min(left + 1, len(AMPLITUDES) - 1)
    blend = position - left
    terms = [
        low + blend * (high - low)
        for low, high in zip(AMPLITUDES[left], AMPLITUDES[right])
    ]
    pairs = list(zip(terms[1::2], terms[2::2]))

    count = 4096
    result = []
    for i in range(count):
        angle = math.tau * i / (count - 1)
        value = terms[0]
        for frequency, (cosine, sine) in enumerate(pairs, start=1):
            value += cosine * math.cos(frequency * angle) + sine * math.sin(frequency * angle)
        result.append(value)
    return result


