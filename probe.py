def probe(t):
    t = min(1.0, max(0.0, t)) if math.isfinite(t) else 0.0
    position = t * (len(AMPLITUDES) - 1)
    left = int(position)
    right = min(left + 1, len(AMPLITUDES) - 1)
    terms = [
        a + (position - left) * (b - a)
        for a, b in zip(AMPLITUDES[left], AMPLITUDES[right])
    ]

    sample_count = 4096
    result = [terms[0]] * sample_count
    for k, (cos_amp, sin_amp) in enumerate(zip(terms[1::2], terms[2::2]), start=1):
        step = math.tau * k / (sample_count - 1)
        for i in range(sample_count):
            angle = step * i
            result[i] += cos_amp * math.cos(angle) + sin_amp * math.sin(angle)
    return result


