SAMPLE_COUNT = 4096


def probe(t):
    t = min(1.0, max(0.0, t)) if math.isfinite(t) else 0.0
    basis = [1.0, t - 0.5]
    basis.extend(math.cos(math.pi * k * t) for k in range(1, 21))
    amplitudes = [
        sum(coefficient * term for coefficient, term in zip(row, basis))
        for row in COEFFICIENTS
    ]

    position = t * (len(TARGETS) - 1)
    left = int(position)
    right = min(left + 1, len(TARGETS) - 1)
    target = TARGETS[left] + (position - left) * (TARGETS[right] - TARGETS[left])

    mean_square = amplitudes[0] ** 2 + sum(a * a for a in amplitudes[1:]) / 2
    scale = min(1.25, math.sqrt(2 * target / mean_square)) if mean_square else 1.25
    harmonics = list(zip(amplitudes[1::2], amplitudes[2::2]))

    samples = []
    for i in range(SAMPLE_COUNT):
        angle = math.tau * i / (SAMPLE_COUNT - 1)
        value = amplitudes[0]
        for k, (cos_amplitude, sin_amplitude) in enumerate(harmonics, start=1):
            value += cos_amplitude * math.cos(k * angle) + sin_amplitude * math.sin(k * angle)
        samples.append(max(-3.0, min(3.0, scale * value)))
    return samples


