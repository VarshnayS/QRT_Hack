# Cosine/sine pairs for the pulse at frequencies 5 through 12.
PULSE = (
    -0.05263776, 0.01960135, 0.04366131, -0.01990617,
    0.02391778, -0.01303725, -0.03516598, 0.02255802,
    -0.00786343, 0.00587489, 0.02625151, -0.02269877,
    -0.00093482, 0.00093266, -0.01788977, 0.02059332,
)
SAMPLES = 4096


def probe(t):
    position = min(1.0, max(0.0, t)) * (len(FIT) - 1)
    left = int(position)
    right = min(left + 1, len(FIT) - 1)
    fraction = position - left
    amplitudes = [x + fraction * (y - x) for x, y in zip(FIT[left], FIT[right])]
    pulse = amplitudes.pop()
    amplitudes.extend(pulse * x for x in PULSE)
    harmonics = list(zip(amplitudes[1::2], amplitudes[2::2]))
    curve = []
    for i in range(SAMPLES):
        angle = math.tau * (i + 0.5) / SAMPLES
        value = amplitudes[0]
        for k, (cosine, sine) in enumerate(harmonics, start=1):
            value += cosine * math.cos(k * angle) + sine * math.sin(k * angle)
        curve.append(value)
    return curve


